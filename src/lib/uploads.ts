import "server-only";
import { randomBytes } from "node:crypto";
import { mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import path from "node:path";

export const MAX_IMAGE_BYTES = 8 * 1024 * 1024;
export const MAX_IMAGES_PER_UPLOAD = 5;

const UPLOAD_DIR = path.resolve(process.cwd(), process.env.UPLOAD_DIR || "uploads");

type ImageType = { mime: string; ext: string };

/** Detects the real image type from magic bytes instead of trusting the client. */
function sniffImageType(buf: Buffer): ImageType | null {
  if (buf.length >= 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return { mime: "image/jpeg", ext: "jpg" };
  if (buf.length >= 8 && buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])))
    return { mime: "image/png", ext: "png" };
  if (buf.length >= 12 && buf.toString("ascii", 0, 4) === "RIFF" && buf.toString("ascii", 8, 12) === "WEBP")
    return { mime: "image/webp", ext: "webp" };
  return null;
}

export class UploadError extends Error {}

/** Returns the non-empty files for a FormData key, validating count and size. */
export function getImageFiles(formData: FormData, key: string) {
  const files = formData.getAll(key).filter((f): f is File => f instanceof File && f.size > 0);
  if (files.length > MAX_IMAGES_PER_UPLOAD) throw new UploadError(`อัปโหลดรูปได้ไม่เกิน ${MAX_IMAGES_PER_UPLOAD} รูป`);
  for (const f of files) {
    if (f.size > MAX_IMAGE_BYTES) throw new UploadError(`ไฟล์ ${f.name} มีขนาดเกิน 8MB`);
  }
  return files;
}

export async function saveImage(file: File) {
  const buf = Buffer.from(await file.arrayBuffer());
  const type = sniffImageType(buf);
  if (!type) throw new UploadError(`ไฟล์ ${file.name} ไม่ใช่รูปภาพที่รองรับ (JPG, PNG, WEBP)`);

  await mkdir(UPLOAD_DIR, { recursive: true });
  const filename = `${Date.now()}-${randomBytes(8).toString("hex")}.${type.ext}`;
  await writeFile(path.join(UPLOAD_DIR, filename), buf);
  return { filename, mimeType: type.mime, size: buf.length };
}

export async function readImage(filename: string) {
  // Stored names are generated by saveImage; reject anything else to prevent path traversal.
  if (!/^[\w-]+\.(jpg|png|webp)$/.test(filename)) return null;
  try {
    return await readFile(path.join(UPLOAD_DIR, filename));
  } catch {
    return null;
  }
}

export async function deleteImages(filenames: string[]) {
  await Promise.all(
    filenames
      .filter((f) => /^[\w-]+\.(jpg|png|webp)$/.test(f))
      .map((f) => unlink(path.join(UPLOAD_DIR, f)).catch(() => undefined)),
  );
}
