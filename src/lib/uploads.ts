import "server-only";
import { del, get, put } from "@vercel/blob";
import { randomBytes } from "node:crypto";
import { mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * Photo storage with two drivers:
 * - Vercel Blob (private store) when a store is connected — BLOB_STORE_ID (OIDC,
 *   set automatically on Vercel) or BLOB_READ_WRITE_TOKEN is present. Serverless
 *   functions have no persistent disk, so this is what production uses.
 * - The local `uploads/` folder otherwise (development).
 * Either way files are only ever served through /api/uploads/[filename], which
 * checks the viewer's permission first.
 */

export const MAX_IMAGE_BYTES = 8 * 1024 * 1024;
export const MAX_IMAGES_PER_UPLOAD = 5;

// Runtime-configurable storage location, so tell the bundler not to trace it
// (otherwise the whole project is pulled into the server output).
const UPLOAD_DIR = path.resolve(/*turbopackIgnore: true*/ process.cwd(), process.env.UPLOAD_DIR || "uploads");
const BLOB_PREFIX = "repair-photos/";
const FILENAME_PATTERN = /^[\w-]+\.(jpg|png|webp)$/;

function blobStorageEnabled() {
  return Boolean(process.env.BLOB_STORE_ID || process.env.BLOB_READ_WRITE_TOKEN);
}

type ImageType = { mime: string; ext: string };

/** Detects the real image type from magic bytes instead of trusting the client. */
function sniffImageType(buf: Buffer): ImageType | null {
  if (buf.length >= 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return { mime: "image/jpeg", ext: "jpg" };
  if (buf.length >= 8 && buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])))
    return { mime: "image/png", ext: "png" };
  if (buf.length >= 12 && buf.toString("ascii", 0, 4) === "RIFF" && buf.toString("ascii", 8, 12) === "WEBP")
    return { mime: "image/webp", ext: "webp" };
  return null;
}

export class UploadError extends Error {}

/** Returns the non-empty files for a FormData key, validating count and size. */
export function getImageFiles(formData: FormData, key: string) {
  const files = formData.getAll(key).filter((f): f is File => f instanceof File && f.size > 0);
  if (files.length > MAX_IMAGES_PER_UPLOAD) throw new UploadError(`อัปโหลดรูปได้ไม่เกิน ${MAX_IMAGES_PER_UPLOAD} รูป`);
  for (const f of files) {
    if (f.size > MAX_IMAGE_BYTES) throw new UploadError(`ไฟล์ ${f.name} มีขนาดเกิน 8MB`);
  }
  return files;
}

export async function saveImage(file: File) {
  const buf = Buffer.from(await file.arrayBuffer());
  const type = sniffImageType(buf);
  if (!type) throw new UploadError(`ไฟล์ ${file.name} ไม่ใช่รูปภาพที่รองรับ (JPG, PNG, WEBP)`);

  const filename = `${Date.now()}-${randomBytes(8).toString("hex")}.${type.ext}`;
  if (blobStorageEnabled()) {
    await put(BLOB_PREFIX + filename, buf, {
      access: "private",
      contentType: type.mime,
      addRandomSuffix: false, // the name is already random and is what we store in the DB
    });
  } else {
    await mkdir(UPLOAD_DIR, { recursive: true });
    await writeFile(path.join(UPLOAD_DIR, filename), buf);
  }
  return { filename, mimeType: type.mime, size: buf.length };
}

export type OpenedImage =
  | { status: 200; body: ReadableStream<Uint8Array> | Uint8Array<ArrayBuffer>; etag: string }
  | { status: 304; etag: string };

/**
 * Opens a stored photo for streaming. Pass the browser's If-None-Match to get a
 * cheap 304 when it already has the file. Returns null when it doesn't exist.
 */
export async function openImage(filename: string, ifNoneMatch?: string | null): Promise<OpenedImage | null> {
  // Stored names are generated by saveImage; reject anything else to prevent path traversal.
  if (!FILENAME_PATTERN.test(filename)) return null;

  if (blobStorageEnabled()) {
    const result = await get(BLOB_PREFIX + filename, { access: "private", ifNoneMatch: ifNoneMatch ?? undefined });
    if (!result) return null;
    return result.statusCode === 304
      ? { status: 304, etag: result.blob.etag }
      : { status: 200, body: result.stream, etag: result.blob.etag };
  }

  // Local files never change, so the name itself works as the ETag.
  const etag = `"${filename}"`;
  if (ifNoneMatch === etag) return { status: 304, etag };
  try {
    return { status: 200, body: new Uint8Array(await readFile(path.join(UPLOAD_DIR, filename))), etag };
  } catch {
    return null;
  }
}

export async function deleteImages(filenames: string[]) {
  const names = filenames.filter((f) => FILENAME_PATTERN.test(f));
  if (names.length === 0) return;
  if (blobStorageEnabled()) {
    await del(names.map((f) => BLOB_PREFIX + f)).catch(() => undefined);
    return;
  }
  await Promise.all(names.map((f) => unlink(path.join(UPLOAD_DIR, f)).catch(() => undefined)));
}
